<#
.SYNOPSIS
    Writes the installer's models include (DECISIONS.md D070 §2, §7) from a models package's models.json: one [Files] line per
    pinned model file (copied into {localappdata}\<DataFolder>\models only when the file in place lacks its SHA-256, never
    removed by the uninstaller on its own) and ModelFolders() — the folders the uninstaller removes when the user ticks
    «Также удалить ИИ-модели». Used by tools/distribution/New-Release.ps1 and tools/installer/Test-Installer.ps1.

    -BaseUrl (the web Setup, D070 §7): the files are not packed into the setup but downloaded from <BaseUrl><file name>
    (the models release's assets) — Inno checks each download's SHA-256 before it takes its place; a file already in place
    with its SHA-256 is not downloaded.
#>
[CmdletBinding()]
param(
    [Parameter(Mandatory)] [string] $ModelsDir,
    [Parameter(Mandatory)] [string] $OutFile,
    [string] $BaseUrl
)

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'

if ($BaseUrl -and -not $BaseUrl.EndsWith('/')) { $BaseUrl += '/' }
$manifest = Get-Content -Raw -Encoding utf8 (Join-Path $ModelsDir 'models.json') | ConvertFrom-Json
$lines = [System.Collections.Generic.List[string]]::new()
$lines.Add('; Generated by tools/installer/New-ModelsInclude.ps1 from the package''s models.json - do not edit.')
$names = @{}
foreach ($folder in $manifest.folders) {
    foreach ($file in $folder.files) {
        $relative = "$($folder.folder)\$($file.name)"
        $destination = "{localappdata}\{#DataFolder}\models\$($folder.folder)"
        $check = "Check: ModelNeeded('$relative', '$($file.sha256)')"
        if ($BaseUrl) {
            # The release's assets are flat: every pinned file name must be unique across the folders.
            if ($names.ContainsKey($file.name)) { throw "Two model files named $($file.name): the web Setup's assets need unique names" }
            $names[$file.name] = $true
            $lines.Add("Source: ""$BaseUrl$($file.name)""; DestName: ""$($file.name)""; DestDir: ""$destination""; Hash: ""$($file.sha256)""; ExternalSize: $($file.length); Flags: external download ignoreversion uninsneveruninstall; $check")
        } else {
            $source = Join-Path $ModelsDir "models\$relative"
            if (-not (Test-Path -LiteralPath $source)) { throw "Missing in the package: $source" }
            $lines.Add("Source: ""$source""; DestDir: ""$destination""; Flags: ignoreversion nocompression uninsneveruninstall; $check")
        }
    }
}
# people-v1: the people models before 1.0 (D066 §3), still in the models folder of earlier installations.
$folders = @($manifest.folders | ForEach-Object { $_.folder }) + 'people-v1'
$lines.Add('')
$lines.Add('[Code]')
$lines.Add('function ModelFolders(): TArrayOfString;')
$lines.Add('begin')
$lines.Add("  SetArrayLength(Result, $($folders.Count));")
for ($i = 0; $i -lt $folders.Count; $i++) { $lines.Add("  Result[$i] := '$($folders[$i])';") }
$lines.Add('end;')
Set-Content -Path $OutFile -Value $lines -Encoding UTF8
